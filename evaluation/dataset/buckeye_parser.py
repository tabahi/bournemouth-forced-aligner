    os.makedirs(os.path.dirname(paths_list_path), exist_ok=True)
    with open(paths_list_path, 'w') as f:
        json.dump(assorted_list_data, f)
    print("Saved assorted_list_data to:", os.path.abspath(paths_list_path))

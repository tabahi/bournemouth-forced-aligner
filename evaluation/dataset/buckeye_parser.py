def get_audio_duration(audio_path):
    """
    Get the duration of an audio file using ffprobe
    
    Args:
        audio_path (str): Path to the audio file
    
    Returns:
        float: Duration in seconds if successful, None if failed
        str: Error message if failed, None if successful
    """
    cmd = [
        "ffprobe", "-v", "error", 
        "-show_entries", "format=duration", 
        "-of", "json", audio_path
    ]
    try:
        result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        metadata = json.loads(result.stdout)
        return float(metadata["format"]["duration"]), None
    except Exception as e:
        return None, str(e)



# Tokens that end a segment outright.  <IVER> is the interviewer speaking; {B_TRANS}
# and {E_TRANS} mark the start and end of the transcription.  {E_TRANS} carries the
# end-of-file timestamp, so treating it as an ordinary word stretched the last segment
# of every file to the end of the recording (s0303b: 215.7 -> 324.9 s holding "just uh").
BREAK_TOKENS = {"<IVER>", "{B_TRANS}", "{E_TRANS}"}


def is_tag_token(word):
    """
    True for the bracketed annotations (<SIL>, <LAUGH>, <VOCNOISE>, {E_TRANS}, ...).

    These are stripped from the transcript, so they are not speech the aligner can
    ever target - which is exactly why they must not define a segment's extent.
    """
    return (word.startswith("<") and word.endswith(">")) or (word.startswith("{") and word.endswith("}"))


def trim_to_speech(words, start_time):
    """
    (start_time, words) narrowed to the first and last SPEECH tokens of the run.

    Timestamps in the .words file are END times, which cuts both ways.  A run that
    ENDS on a tag inherits that tag's whole extent - one <LAUGH> in s0305a spans
    111.5 s and turned a 9 s segment into a 120.7 s one.  A run that STARTS on tags
    carries their silence as leading padding, because the run began at the end of the
    preceding break token; dropping them and taking the last one's timestamp gives the
    exact instant the first real word begins.

    Returns (start_time, []) when the run holds no speech at all.
    """
    speech = [i for i, w in enumerate(words) if not is_tag_token(w["word"])]
    if not speech:
        return start_time, []
    first, last = speech[0], speech[-1]
    if first > 0:
        start_time = max(start_time, words[first - 1]["timestamp"])
    return start_time, words[first:last + 1]


def save_srt(audio_path, srt_path, duration=0, phones_data=None, boundaries=None, words_data=None, max_duration=max_duration, target_duration=target_duration):
    # `audio_path` is unused since the librosa energy trim was deleted - segment ends
    # come from the .words annotation now, which is exact.  The parameter stays because
    # every caller passes it positionally and silently shifting srt_path would write an
    # SRT over a wav.
    clean_duration = 0
    def make_segment(seg_start, seg_words):
        """
        One segment dict from a run of words, or None when the run holds no text.

        The segment spans its first SPEECH token to its last, never a leading or
        trailing tag, and the boundaries are collected over exactly that span - so the
        ground truth can no longer describe a stretch of audio the segment does not
        cover, at either end.
        """
        seg_start, seg_words = trim_to_speech(seg_words, seg_start)
        if not seg_words:
            return None

        seg_end = seg_words[-1]["timestamp"]
        if seg_end <= seg_start:
            return None

        seg_text = clean_text_buckeye(" ".join(w["word"] for w in seg_words
                                               if not is_tag_token(w["word"])))
        if not seg_text.strip():
            return None

        # `boundaries` are absolute ms from the .phones file; stored segment-relative.
        seg_boundaries = []
        if boundaries:
            for boundary in boundaries:
                boundary_time = boundary / 1000.0
                if seg_start <= boundary_time <= seg_end:
                    seg_boundaries.append(int((boundary_time - seg_start) * 1000))

        return {"start": seg_start, "end": seg_end, "text": seg_text, "boundaries": seg_boundaries}

    if words_data is not None:
        # Each entry: (start_time, [word_infos])
        # Timestamps in the words file are END times of each token.
        # start_time = end of the preceding break token (or 0.0 for the first segment)
        # Consecutive break tokens (no subject speech between them) are handled
        # correctly here because prev_break_time is updated on every one of them.
        segments_info = []
        prev_break_time = 0.0
        current_segment_words = []

        for word_info in words_data:
            if word_info["word"] in BREAK_TOKENS:
                if current_segment_words:
                    segments_info.append((prev_break_time, current_segment_words))
                    current_segment_words = []
                prev_break_time = word_info["timestamp"]
            else:
                current_segment_words.append(word_info)

        if current_segment_words:
            segments_info.append((prev_break_time, current_segment_words))

        segments = []

        for start_time, seg_words in segments_info:
            # Leading and trailing tags carry no speech and only stretch the run, so the
            # length that decides whether to split is measured speech-to-speech.
            start_time, seg_words = trim_to_speech(seg_words, start_time)
            if not seg_words:
                continue
            end_time = seg_words[-1]["timestamp"]
            if end_time <= start_time:
                continue

            # Break long segments based on duration
            if end_time - start_time > max_duration:
                print(f"Breaking long segment: {end_time - start_time:.1f}s")
                # Split this segment into smaller chunks
                current_start = start_time
                current_words = []

                for word_info in seg_words:
                    word = word_info["word"]
                    word_time = word_info["timestamp"]

                    # A chunk's clock starts at its first word, so silence that follows a
                    # break only moves the start forward - it never eats into the budget
                    # and never lands inside a segment.
                    if not current_words and is_tag_token(word):
                        current_start = word_time
                        continue

                    # Add current word first
                    current_words.append(word_info)
                    current_duration = word_time - current_start

                    # Check if we should break at this point
                    should_break = False

                    if current_duration >= max_duration:
                        # Force break at max duration - must break here
                        should_break = True
                    elif current_duration >= target_duration and word == "<SIL>":
                        # Natural break at SIL after target duration
                        should_break = True

                    if should_break:
                        segment = make_segment(current_start, current_words)
                        if segment is not None:
                            segments.append(segment)
                            clean_duration += segment["end"] - segment["start"]
                        # The token that crossed the threshold may itself be a long
                        # <SIL>/<LAUGH>; the next chunk starts after IT, not after the
                        # speech that preceded it, so the silence belongs to neither.
                        current_start = word_time
                        current_words = []
                        
                # Handle remaining words
                if current_words:
                    segment = make_segment(current_start, current_words)
                    if segment is not None:
                        segments.append(segment)
                        clean_duration += segment["end"] - segment["start"]
            else:
                # Segment is short enough, process normally
                segment = make_segment(start_time, seg_words)
                if segment is not None:
                    segments.append(segment)
                    clean_duration += segment["end"] - segment["start"]

        srt_data = {"segments": segments, "voiced_duration": clean_duration}
    else:
        print("No words data provided, creating empty SRT.")
        srt_data = {"segments": [], "voiced_duration": clean_duration}

    if phones_data is not None:
        srt_data["phones"] = phones_data


    with open(srt_path, 'w') as f:
        json.dump(srt_data, f)
        print(f"Saved SRT to {srt_path}")
    return clean_duration

def clean_text_buckeye(text):
    # Implement any specific cleaning for Buckeye text here
    text = text.strip()
    # replace <IVER> with ...
    text = re.sub(r"<IVER>", "...", text)

    # replace SIL with , <SIL>
    text = re.sub(r"<SIL>", ", ", text)

    # remove any tokens with <> tags
    text = re.sub(r"<[^>]+>", "", text)

    return text


def read_phones(phones_file_path):
    
    #print(f"Reading phones from {phones_file_path}")
    with open(phones_file_path, 'r') as f:
        lines = f.readlines()
    phone_lines = [line.strip() for line in lines if line.strip()]
    
    phones = []
    boundaries = []
    start=False
    for i, pline in enumerate(phone_lines):
        
        if start:
            parts = pline.split()
            if len(parts) >= 3:
                if (parts[2].strip()=="{E_TRANS}") or i >= len(phone_lines)-1:
                    break

            next_parts = phone_lines[i + 1].split()
            
            time_start = round(float(parts[0])*1000)
            time_end = round(float(next_parts[0])*1000)
            if len(parts) < 3:
                continue

            phone_value = parts[2].strip()
            if (phone_value=="VOCNOISE"):
                phone_value = "noise"
            elif (phone_value=="LAUGH"):
                phone_value = "SIL"
            elif (phone_value=="SIL"):
                phone_value = "SIL"
            elif (phone_value=="IVER"):
                phone_value = "SIL"

            phones.append({"start": time_start, "end": time_end, "phone": phone_value})
            boundaries.append(time_start)
            if time_end not in boundaries:
                boundaries.append(time_end)
        elif pline.strip() == "#":
                start = True
    
    return phones, boundaries


def read_words(words_file_path):

    with open(words_file_path, 'r') as f:
        lines = f.readlines()
    word_lines = [line.strip() for line in lines if line.strip()]

    words = []
    for wline in word_lines:
        parts = wline.split()
        if len(parts) >= 3:
            word_value = parts[2].strip()
            words.append(word_value)

    return words

def read_words_with_timing(words_file_path):
    with open(words_file_path, 'r') as f:
        lines = f.readlines()
    word_lines = [line.strip() for line in lines if line.strip()]

    words_data = []
    start_parsing = False
    
    for wline in word_lines:
        if wline.strip() == "#":
            start_parsing = True
            continue
        
        if not start_parsing:
            continue
            
        parts = wline.split()
        if len(parts) >= 3:
            timestamp = float(parts[0])
            word_part = parts[2].strip()
            if ';' in word_part:
                word_value = word_part.split(';')[0].strip()
            else:
                word_value = word_part
            words_data.append({
                "timestamp": timestamp,
                "word": word_value
            })

    return words_data

def assort_paths(setname="all", redo_srts=False):

    assert setname in all_sets, f"Invalid setname: {setname}"

    total_spkr = 40
    
    if not os.path.exists(transcription_dir):
        os.makedirs(transcription_dir)
        

    
    paths_list = []
    total_duration = 0.0
    total_vdur = 0.0

    for spkr in tqdm(range(1, total_spkr+1), desc="Assorting dataset"):
        # buckeye_corpus/s40/s4004a/s4004a.wav
        spkr_dir = os.path.join(buckeye_base_dir, f"s{spkr:02d}")
        wav_files = glob.glob(os.path.join(spkr_dir.strip(), '*/*.wav'))
        
        for clip_id in range(len(wav_files)):
            audio_path = wav_files[clip_id]
            # Process each clip as needed

            duration, error = get_audio_duration(audio_path)
            if error:
                print(f"Failed to process {audio_path}: {error}")
                continue
            total_duration += duration

            
            phone_path = audio_path.replace('.wav', '.phones')
            words_path = audio_path.replace('.wav', '.words')

            clip_basename = os.path.basename(audio_path).split('.wav')[0]
            

            specific_dir = os.path.join(transcription_dir,  f"s{spkr:02d}".strip())
    
            srt_path = os.path.join(specific_dir, clip_basename + '.srt.json')
            os.makedirs(specific_dir, exist_ok=True)
            
            if (not os.path.exists(phone_path)):
                print(f"Warning: {phone_path} does not exist.")
                continue
            phones, boundaries = read_phones(phone_path)
            
            words_data = None
            if os.path.exists(words_path):
                words_data = read_words_with_timing(words_path)
            
            if redo_srts or (not os.path.exists(srt_path)):
                if words_data:
                    vdur = save_srt(audio_path, srt_path, duration, phones_data=phones, boundaries=boundaries, words_data=words_data, max_duration=30, target_duration=10)
                    total_vdur += vdur

                else:
                    print(f"WARN: Words file not found for {audio_path.split('/')[-1]}, skipping SRT creation")

            
            clip_obj = { 'audio': audio_path.replace(buckeye_base_dir, '~'),
                        'srt': srt_path, 'set': setname, 'lang': 'en', 'duration': duration, 
                        'spkr': spkr, 'clip_id': clip_id, 'sex': 'X'}
            
            paths_list.append(clip_obj)

    print("Total clips processed:", len(paths_list), "Total duration (h):", round(total_duration/3600, 2), "Total voiced duration (h):", round(total_vdur/3600, 2))

    return paths_list



